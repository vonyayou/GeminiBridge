test('Responses accepts arbitrary API keys and works without Authorization', async ({ request }) => {
  for (const key of [null, 'x', 'local', 'any-client-key']) {
    const headers = key ? { Authorization: `Bearer ${key}` } : {}
    const ordinary = await request.post('/v1/responses', { headers, data: { model: 'gemini-3.1-pro', input: 'client test' } })
    expect(ordinary.status()).toBe(200)
    expect((await ordinary.json()).output[0].content[0].text).toContain('client test')
  }
  const streamed = await request.post('/v1/responses', { headers: { Authorization: 'Bearer arbitrary' }, data: { model: 'gemini-3.1-pro', input: 'stream test', stream: true } })
  expect(streamed.status()).toBe(200)
  const events = (await streamed.text()).split('\n').filter(line => line.startsWith('data:')).map(line => JSON.parse(line.slice(5)))
  expect(events[0].type).toBe('response.created')
  expect(events.at(-1).type).toBe('response.completed')
  const dashboard = await request.get('/api/dashboard')
  expect(dashboard.status()).toBe(200)
})

test('manual cookies connect directly and are never returned or stored by the panel', async ({ page, request }) => {
  await page.getByRole('link', { name: 'Settings', exact: true }).click()
  await page.getByLabel('Session source', { exact: true }).selectOption('manual')
  await page.getByLabel('__Secure-1PSID', { exact: true }).fill('manual-test-session-cookie')
  await page.getByLabel('__Secure-1PSIDTS', { exact: true }).fill('manual-test-timestamp-cookie')
  await page.getByRole('button', { name: 'Connect with entered cookies', exact: true }).click()
  await expect(page.getByText('Connected', { exact: true })).toBeVisible()
  await expect(page.getByLabel('__Secure-1PSID', { exact: true })).toHaveValue('')
  const status = await request.get('/api/auth/status')
  const body = await status.json()
  expect(body.source).toBe('manual')
  expect(body.accountEmail).toBe('tester@example.com')
  expect(JSON.stringify(body)).not.toContain('manual-test-session-cookie')
  expect(await page.evaluate(() => JSON.stringify(localStorage))).not.toContain('manual-test-session-cookie')
  await page.getByLabel('Session source', { exact: true }).selectOption('browser')
  await page.getByRole('button', { name: 'Reconnect browser session', exact: true }).click()
  await expect.poll(async () => (await (await request.get('/api/auth/status')).json()).source).toBe('browser')
})
